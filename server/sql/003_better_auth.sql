-- Tables used by Better Auth. Run this before deploying the server that uses Better Auth,
-- then run `pnpm migrate:auth` to copy existing credentials into them.
-- Safe to run more than once. Legacy auth columns on users are left in place.

BEGIN;

-- Better Auth always addresses the user key as "id". This read-only copy of userid lets it do
-- that without touching the foreign keys and queries that use userid.
ALTER TABLE users ADD COLUMN IF NOT EXISTS id INTEGER GENERATED ALWAYS AS (userid) STORED;
CREATE UNIQUE INDEX IF NOT EXISTS users_id_key ON users (id);

ALTER TABLE users ADD COLUMN IF NOT EXISTS "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW();
UPDATE users SET "createdAt" = NOW() WHERE "createdAt" IS NULL;
ALTER TABLE users ALTER COLUMN "createdAt" SET NOT NULL;
-- Passwords now live in accounts, so new users have nothing to store here.
ALTER TABLE users ALTER COLUMN password DROP NOT NULL;

CREATE TABLE IF NOT EXISTS sessions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token       TEXT NOT NULL UNIQUE,
  "userId"    INTEGER NOT NULL REFERENCES users (userid) ON DELETE CASCADE,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  "ipAddress" TEXT,
  "userAgent" TEXT,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON sessions ("userId");

CREATE TABLE IF NOT EXISTS accounts (
  id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId"                INTEGER NOT NULL REFERENCES users (userid) ON DELETE CASCADE,
  "providerId"            TEXT NOT NULL,
  "accountId"             TEXT NOT NULL,
  password                TEXT,
  "accessToken"           TEXT,
  "refreshToken"          TEXT,
  "idToken"               TEXT,
  "accessTokenExpiresAt"  TIMESTAMPTZ,
  "refreshTokenExpiresAt" TIMESTAMPTZ,
  scope                   TEXT,
  "createdAt"             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  "updatedAt"             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE ("providerId", "accountId")
);
CREATE INDEX IF NOT EXISTS accounts_user_id_idx ON accounts ("userId");

CREATE TABLE IF NOT EXISTS verifications (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identifier  TEXT NOT NULL,
  value       TEXT NOT NULL,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS verifications_identifier_idx ON verifications (identifier);

CREATE TABLE IF NOT EXISTS two_factors (
  id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId"                  INTEGER NOT NULL UNIQUE REFERENCES users (userid) ON DELETE CASCADE,
  secret                    TEXT NOT NULL,
  "backupCodes"             TEXT NOT NULL,
  verified                  BOOLEAN,
  "failedVerificationCount" INTEGER,
  "lockedUntil"             TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS two_factors_secret_idx ON two_factors (secret);

CREATE TABLE IF NOT EXISTS passkeys (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId"       INTEGER NOT NULL REFERENCES users (userid) ON DELETE CASCADE,
  "credentialID" TEXT NOT NULL UNIQUE,
  "publicKey"    TEXT NOT NULL,
  counter        INTEGER NOT NULL DEFAULT 0,
  "deviceType"   TEXT NOT NULL,
  "backedUp"     BOOLEAN NOT NULL,
  transports     TEXT,
  name           TEXT,
  aaguid         TEXT,
  "createdAt"    TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS passkeys_user_id_idx ON passkeys ("userId");

COMMIT;
